-- =============================================================================
-- V1__init_schema.sql
-- HireHub - initial relational schema.
--
-- Conventions used throughout:
--   * surrogate BIGINT identity primary keys (business data such as email changes;
--     primary keys must not)
--   * TIMESTAMPTZ for every instant, DATE only for calendar-only values
--   * enums stored as VARCHAR + CHECK, never native PG enum types and never ordinals
--   * every named constraint is prefixed: pk_ / fk_ / uq_ / ck_ / idx_
-- =============================================================================

-- Trigram support for keyword search on job titles (see idx_jobs_title_trgm below).
CREATE EXTENSION IF NOT EXISTS pg_trgm;


-- -----------------------------------------------------------------------------
-- roles : lookup table. One role per user in this system.
-- -----------------------------------------------------------------------------
CREATE TABLE roles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(20) NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT ck_roles_name CHECK (name IN ('ADMIN', 'RECRUITER', 'CANDIDATE'))
);


-- -----------------------------------------------------------------------------
-- users : authentication identity. Profile data lives in the two profile tables
-- so that the login path reads a narrow row.
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    phone         VARCHAR(20),
    role_id       BIGINT       NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_users PRIMARY KEY (id),
    -- Emails are normalised to lower case by the application before insert, so a plain
    -- UNIQUE constraint is enough and it doubles as the index for the login lookup.
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- PostgreSQL indexes the referenced PK, never the referencing column: without this,
-- "which users hold role X" and the FK check on role deletion are sequential scans.
CREATE INDEX idx_users_role_id ON users (role_id);


-- -----------------------------------------------------------------------------
-- companies : approved by an admin before their jobs can be published.
-- -----------------------------------------------------------------------------
CREATE TABLE companies (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR(150) NOT NULL,
    website      VARCHAR(255),
    description  TEXT,
    industry     VARCHAR(100),
    company_size VARCHAR(30),
    logo_url     VARCHAR(512),
    status       VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_companies PRIMARY KEY (id),
    CONSTRAINT uq_companies_name UNIQUE (name),
    CONSTRAINT ck_companies_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- Admin moderation queue: WHERE status = 'PENDING' ORDER BY created_at.
CREATE INDEX idx_companies_status_created_at ON companies (status, created_at);


-- -----------------------------------------------------------------------------
-- recruiter_profiles : one-to-one with users. The UNIQUE on user_id is what makes
-- it one-to-one rather than one-to-many.
-- -----------------------------------------------------------------------------
CREATE TABLE recruiter_profiles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT      NOT NULL,
    company_id  BIGINT,
    designation VARCHAR(100),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_recruiter_profiles PRIMARY KEY (id),
    CONSTRAINT uq_recruiter_profiles_user UNIQUE (user_id),
    -- Deleting the account deletes the profile: the profile is meaningless without it.
    CONSTRAINT fk_recruiter_profiles_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    -- company_id is nullable: a recruiter registers first, then creates or joins a company.
    -- RESTRICT, because deleting a company with staff attached should be a deliberate act.
    CONSTRAINT fk_recruiter_profiles_company FOREIGN KEY (company_id)
        REFERENCES companies (id) ON DELETE RESTRICT
);

CREATE INDEX idx_recruiter_profiles_company ON recruiter_profiles (company_id);


-- -----------------------------------------------------------------------------
-- candidate_profiles : one-to-one with users.
-- -----------------------------------------------------------------------------
CREATE TABLE candidate_profiles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT      NOT NULL,
    headline         VARCHAR(150),
    summary          TEXT,
    experience_years INTEGER     NOT NULL DEFAULT 0,
    current_location VARCHAR(120),
    expected_salary  NUMERIC(12, 2),
    resume_url       VARCHAR(512),
    resume_file_name VARCHAR(255),
    linkedin_url     VARCHAR(255),
    github_url       VARCHAR(255),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_candidate_profiles PRIMARY KEY (id),
    CONSTRAINT uq_candidate_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_candidate_profiles_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    -- Bean Validation says the same thing, but the DB is the only place that holds
    -- for every writer, including manual SQL and future services.
    CONSTRAINT ck_candidate_profiles_experience CHECK (experience_years BETWEEN 0 AND 60),
    CONSTRAINT ck_candidate_profiles_salary CHECK (expected_salary IS NULL OR expected_salary >= 0)
);


-- -----------------------------------------------------------------------------
-- skills : shared vocabulary. Names are normalised to lower case by the application
-- so that "Java", "java" and "JAVA" collapse into one row.
-- -----------------------------------------------------------------------------
CREATE TABLE skills (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_skills PRIMARY KEY (id),
    CONSTRAINT uq_skills_name UNIQUE (name),
    CONSTRAINT ck_skills_name_lowercase CHECK (name = lower(name))
);


-- -----------------------------------------------------------------------------
-- candidate_skills : many-to-many WITH payload, so it is a first-class table with a
-- composite primary key rather than a hidden @ManyToMany join table.
-- -----------------------------------------------------------------------------
CREATE TABLE candidate_skills (
    candidate_profile_id BIGINT      NOT NULL,
    skill_id             BIGINT      NOT NULL,
    proficiency          VARCHAR(20) NOT NULL DEFAULT 'INTERMEDIATE',
    years_of_experience  INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT pk_candidate_skills PRIMARY KEY (candidate_profile_id, skill_id),
    CONSTRAINT fk_candidate_skills_candidate FOREIGN KEY (candidate_profile_id)
        REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_candidate_skills_skill FOREIGN KEY (skill_id)
        REFERENCES skills (id) ON DELETE RESTRICT,
    CONSTRAINT ck_candidate_skills_proficiency
        CHECK (proficiency IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT')),
    CONSTRAINT ck_candidate_skills_years CHECK (years_of_experience BETWEEN 0 AND 60)
);

-- The composite PK already indexes (candidate_profile_id, skill_id) and therefore serves
-- "skills of candidate X". The reverse lookup "candidates who know skill Y" needs its own
-- index because a composite index cannot be used for its trailing column alone.
CREATE INDEX idx_candidate_skills_skill ON candidate_skills (skill_id);


-- -----------------------------------------------------------------------------
-- jobs
-- -----------------------------------------------------------------------------
CREATE TABLE jobs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    company_id           BIGINT       NOT NULL,
    created_by           BIGINT       NOT NULL,
    title                VARCHAR(150) NOT NULL,
    description          TEXT         NOT NULL,
    location             VARCHAR(120) NOT NULL,
    employment_type      VARCHAR(30)  NOT NULL,
    experience_level     VARCHAR(30)  NOT NULL,
    salary_min           NUMERIC(12, 2),
    salary_max           NUMERIC(12, 2),
    currency             VARCHAR(3)   NOT NULL DEFAULT 'INR',
    openings             INTEGER      NOT NULL DEFAULT 1,
    status               VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    application_deadline DATE,
    published_at         TIMESTAMPTZ,
    closed_at            TIMESTAMPTZ,
    -- Optimistic locking: two recruiters editing the same job -> the second write fails
    -- with a version mismatch instead of silently overwriting the first.
    version              BIGINT       NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_jobs PRIMARY KEY (id),
    CONSTRAINT fk_jobs_company FOREIGN KEY (company_id)
        REFERENCES companies (id) ON DELETE CASCADE,
    CONSTRAINT fk_jobs_created_by FOREIGN KEY (created_by)
        REFERENCES recruiter_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT ck_jobs_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED', 'EXPIRED')),
    CONSTRAINT ck_jobs_employment_type CHECK (employment_type IN
        ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERNSHIP', 'TEMPORARY')),
    CONSTRAINT ck_jobs_experience_level CHECK (experience_level IN
        ('INTERNSHIP', 'ENTRY_LEVEL', 'MID_LEVEL', 'SENIOR_LEVEL', 'LEAD', 'EXECUTIVE')),
    CONSTRAINT ck_jobs_openings CHECK (openings > 0),
    CONSTRAINT ck_jobs_salary_non_negative
        CHECK (salary_min IS NULL OR salary_min >= 0),
    -- A CHECK with a NULL operand evaluates to UNKNOWN and therefore passes, so this
    -- only constrains rows where both bounds were supplied.
    CONSTRAINT ck_jobs_salary_range
        CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_max >= salary_min)
);

-- Default job feed: WHERE status = 'PUBLISHED' ORDER BY created_at DESC LIMIT n.
-- Composite in this order so the equality predicate filters and the second column
-- supplies the ordering - one index scan, no separate sort.
CREATE INDEX idx_jobs_status_created_at ON jobs (status, created_at DESC);

-- Location filtering is case-insensitive (lower(location) = lower(?)). A plain index on
-- location would never be chosen for that predicate; a functional index matches it exactly.
CREATE INDEX idx_jobs_location ON jobs (lower(location));

-- Keyword search uses title ILIKE '%java%'. A B-tree cannot serve a leading wildcard,
-- so this is a GIN trigram index. Full-text (tsvector) is the next step if partial-word
-- matching stops being enough.
CREATE INDEX idx_jobs_title_trgm ON jobs USING gin (title gin_trgm_ops);

-- Recruiter dashboard: "all jobs posted by my company".
CREATE INDEX idx_jobs_company_id ON jobs (company_id);
CREATE INDEX idx_jobs_created_by ON jobs (created_by);


-- -----------------------------------------------------------------------------
-- job_skills : many-to-many with payload (mandatory vs nice-to-have).
-- -----------------------------------------------------------------------------
CREATE TABLE job_skills (
    job_id    BIGINT  NOT NULL,
    skill_id  BIGINT  NOT NULL,
    mandatory BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_job_skills PRIMARY KEY (job_id, skill_id),
    CONSTRAINT fk_job_skills_job FOREIGN KEY (job_id)
        REFERENCES jobs (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_skills_skill FOREIGN KEY (skill_id)
        REFERENCES skills (id) ON DELETE RESTRICT
);

-- "Jobs requiring skill Y" - the trailing column of the composite PK again.
CREATE INDEX idx_job_skills_skill ON job_skills (skill_id);


-- -----------------------------------------------------------------------------
-- applications : the many-to-many between candidates and jobs, carrying state.
-- -----------------------------------------------------------------------------
CREATE TABLE applications (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id               BIGINT      NOT NULL,
    candidate_profile_id BIGINT      NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'APPLIED',
    cover_letter         TEXT,
    resume_url           VARCHAR(512),
    version              BIGINT      NOT NULL DEFAULT 0,
    applied_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_applications PRIMARY KEY (id),
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id)
        REFERENCES jobs (id) ON DELETE CASCADE,
    CONSTRAINT fk_applications_candidate FOREIGN KEY (candidate_profile_id)
        REFERENCES candidate_profiles (id) ON DELETE CASCADE,
    -- THE duplicate-application guard. The service also checks first so the user gets a
    -- friendly 409, but only this constraint holds when two requests race: both can pass
    -- the read, only one can pass the unique index.
    CONSTRAINT uq_applications_job_candidate UNIQUE (job_id, candidate_profile_id),
    CONSTRAINT ck_applications_status CHECK (status IN
        ('APPLIED', 'UNDER_REVIEW', 'SHORTLISTED', 'INTERVIEW', 'SELECTED', 'REJECTED', 'WITHDRAWN'))
);

-- Candidate dashboard: "my applications, optionally filtered by status".
CREATE INDEX idx_applications_candidate_status ON applications (candidate_profile_id, status);

-- Recruiter pipeline: "applicants for job X in stage SHORTLISTED".
CREATE INDEX idx_applications_job_status ON applications (job_id, status);


-- -----------------------------------------------------------------------------
-- application_status_history : append-only audit trail. Rows are never updated or
-- deleted by the application; that is what makes it trustworthy evidence.
-- -----------------------------------------------------------------------------
CREATE TABLE application_status_history (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id     BIGINT      NOT NULL,
    from_status        VARCHAR(20),            -- NULL for the initial APPLIED row
    to_status          VARCHAR(20) NOT NULL,
    changed_by_user_id BIGINT,                 -- NULL if the actor was later deleted
    note               TEXT,
    changed_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_application_status_history PRIMARY KEY (id),
    CONSTRAINT fk_ash_application FOREIGN KEY (application_id)
        REFERENCES applications (id) ON DELETE CASCADE,
    -- SET NULL, not CASCADE: deleting a user must never erase the hiring decisions
    -- they made. The trail survives the actor.
    CONSTRAINT fk_ash_changed_by FOREIGN KEY (changed_by_user_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_ash_to_status CHECK (to_status IN
        ('APPLIED', 'UNDER_REVIEW', 'SHORTLISTED', 'INTERVIEW', 'SELECTED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_ash_from_status CHECK (from_status IS NULL OR from_status IN
        ('APPLIED', 'UNDER_REVIEW', 'SHORTLISTED', 'INTERVIEW', 'SELECTED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_ash_transition CHECK (from_status IS NULL OR from_status <> to_status)
);

-- Renders one application's timeline in chronological order.
CREATE INDEX idx_ash_application_changed_at ON application_status_history (application_id, changed_at);
